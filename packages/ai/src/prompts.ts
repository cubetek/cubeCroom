export type PromptInput = {
  readonly action: AiAction;
  readonly content: string;
  readonly instructions?: string | undefined;
  readonly context?: TeacherAiContext | undefined;
};

const SUPPORT_INSTRUCTIONS: Readonly<Record<TeacherAiContext['support'], string>> = {
  balanced: 'قدّم دعماً متوازناً ثم فرصة للمحاولة المستقلة.',
  scaffolded:
    'استعمل خطوات أصغر، واشرح المصطلحات بمثال محسوس، وقدّم تلميحات تتناقص مع الممارسة دون حذف ناتج التعلم.',
  challenge:
    'حافظ على ناتج التعلم واطلب المقارنة والتبرير ونقل الفكرة إلى سياق جديد، دون افتراض دراسة محتوى غير موجود.',
};

export function buildMessages({
  action,
  content,
  instructions,
  context = DEFAULT_TEACHER_AI_CONTEXT,
}: PromptInput): AiMessage[] {
  const task =
    action === 'custom'
      ? (instructions ?? '').trim() || AI_ACTION_LABELS.custom
      : INSTRUCTIONS[action];

  return [
    { role: 'system', content: SYSTEM },
    // النصّ بعد التعليمة وبفاصل واضح: نموذجٌ يخلط بينهما ينفّذ ما في الدرس
    // بوصفه أمراً — وهو ما يجعل نصّاً في درس يغيّر سلوك الطلب.
    {
      role: 'user',
      content: `${task}\n\nسياق التدريس: المرحلة ${TEACHER_AI_STAGES.find((stage) => stage.value === context.stage)?.label}. مدة الحصة ${context.durationMinutes} دقيقة. ${SUPPORT_INSTRUCTIONS[context.support]}\n\n--- النصّ ---\n${content.trim()}`,
    },
  ];
}
