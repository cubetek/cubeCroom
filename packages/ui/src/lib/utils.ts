import { clsx, type ClassValue } from 'clsx';
import { extendTailwindMerge } from 'tailwind-merge';

/**
 * **`twMerge` بإعدادها الأصليّ تحذف الألوان.**
 *
 * مجموعة `text-` عندها واحدة: مقاسُ الخطّ ولونُه يتزاحمان فيها. وسلّمُ
 * المقاسات في `globals.css` رموزٌ من عندنا (`--text-t-body` · `--text-s-body`)
 * لا من لوحة الإطار، فلا تعرفها؛ تقرأ `text-t-body` لوناً، وترى
 * `text-primary-foreground` منافساً له، فتُبقي الأخير وتحذف الأوّل:
 *
 *     twMerge('text-primary-foreground text-t-body') === 'text-t-body'
 *
 * وأثرُه أنّ الزرّ الأساسيّ — القدوة نفسها — يرث `--color-foreground` على
 * `--color-primary`: نحو 2.5:1 بدل 5.47:1 المقيسة بجانب الرمز. عطلٌ لا يكسر
 * ترجمةً ولا يوقف فحصاً، ويقع في كلّ مكوّن يجمع مقاساً إلى لون.
 *
 * فتُعلَّم القاعدة صراحةً: كلّ قيمةٍ بعد `text-` تبدأ بـ`t-` أو `s-` مقاسٌ،
 * وما سواها لون. و`theme: { text: [...] }` لا تكفي هنا — جُرِّبت فلم تغيّر
 * شيئاً؛ التصنيف نفسه هو ما يحتاج التوسعة لا قائمةُ قيم الرمز.
 */
const isTypeScale = (value: string) => /^[ts]-[a-z0-9-]+$/.test(value);

const twMerge = extendTailwindMerge({
  extend: { classGroups: { 'font-size': [{ text: [isTypeScale] }] } },
});

/**
 * دمج أصناف Tailwind — **مع حسم التعارض، لا مجرّد ضمّ**.
 *
 * `clsx` يجمع الأصناف الشرطية في سلسلة واحدة، و`twMerge` يحذف المتعارض منها
 * فيبقى الأخير: `cn('p-2', 'p-4')` تعطي `p-4` لا `p-2 p-4`.
 *
 * **والفرق ليس تجميلاً.** مكوّنٌ يقبل `className` من مستدعيه ليغيّر حشوه، ثم
 * يضمّ الصنفين بمسافة، يترك الترجيح لترتيب القواعد في الورقة المبنيّة — وهو
 * ترتيبٌ لا يعرفه من يكتب الاستدعاء ولا يملك تغييره. فيصير التجاوز يعمل
 * أحياناً ولا يعمل أحياناً، بلا سببٍ ظاهر في الشيفرة.
 *
 * وهذه الدالة عقد كل مكوّن في `components/ui`: كلٌّ يضمّ أصنافه الأساسية إلى
 * `className` الوارد من خلالها.
 */
export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs));
}
