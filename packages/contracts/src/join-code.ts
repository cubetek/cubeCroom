/**
 * رمز دخول الحصة — §22.
 *
 * ستّ خانات يكتبها المعلم على السبورة ويكتبها الطالب على لوحة مفاتيح.
 *
 * **وهو حارسٌ لا زينة.** قبله كان أيّ جهاز على شبكة المدرسة يجد المنفذ فيرسل
 * طلب دخول — واسمٌ في قائمة المعلم لا يعرفه أحد. وبعده لا يصل الطلب إلا ممّن
 * رأى السبورة، أي ممّن في الغرفة.
 *
 * ولا يُغني عن موافقة المعلم ولا يُنقصها (FR-005): الطلب يبقى معلَّقاً حتى
 * يبتّ فيه. الرمز يمنع الضجيج، والموافقة تمنح الوصول.
 *
 * وهو هنا لا في `core` لأنّ الطرفين الثلاثة يحتاجونه: شاشة المعلم تعرضه
 * (متصفّح لا يملك `node:crypto`)، وخادم الطلاب يقارنه، والمولّد وحده — وهو
 * الذي يحتاج مصدر تشفير — يبقى في `core`.
 */

/**
 * أرقام لا حروف.
 *
 * حروفٌ عربية أو لاتينية على لوحة مفاتيح طفل تعني تبديل اللغة ثم الكتابة ثم
 * التبديل ثانيةً — وأخطاءً في `1/l` و`0/O`. والأرقام تُكتب من صفّ واحد بأي
 * تخطيط لوحة.
 */
export const JOIN_CODE_DIGITS = 6;

/**
 * يُعرض «٤٨٢ ٩١٧» لا «٤٨٢٩١٧».
 *
 * ستّة أرقام متلاصقة تُقرأ خطأً عن بُعد، والمعلم يكتبها على سبورة يراها آخر
 * الصفّ. والفراغ يُعرض ولا يُطلب: ما يكتبه الطالب يُنظَّف قبل المقارنة.
 */
export function formatJoinCode(code: string): string {
  const digits = normalizeJoinCode(code);
  if (digits.length !== JOIN_CODE_DIGITS) return code;
  return `${digits.slice(0, 3)} ${digits.slice(3)}`;
}

/**
 * يُنظّف ما كتبه الطالب قبل المقارنة.
 *
 * الأرقام العربية `٠–٩` تُحوَّل إلى لاتينية، والفراغات والشرطات تُحذف: طالبٌ
 * كتب «٤٨٢-٩١٧» أو «482 917» كتب الرمز الصحيح — ورفضُه لأنه أضاف شرطة عقوبة
 * على شيء لا يخصّ الأمان.
 */
export function normalizeJoinCode(input: string): string {
  return toLatinDigits(input.trim()).replace(/[^0-9]/g, '');
}

/**
 * الأرقام العربية `٠–٩` إلى لاتينية — **الأصل الواحد لهذا التحويل**.
 *
 * كان مكتوباً ثلاث مرات: هنا، وفي `packages/ui/numerals.ts`، وفي محلّل اقتراح
 * التقييم. وثلاث نسخ من تحويلٍ واحد تعني ثلاثة أماكن يجب أن تتفق على ما
 * يُعدّ رقماً — وهي لا تتفق إلا بالصدفة.
 *
 * وموضعه هنا لا في `ui`: تلك حزمة مكوّنات React، و`ai` لا يجوز أن يعتمد
 * عليها ليحوّل رقماً. و`contracts` هي الحزمة الأساس التي يعتمد عليها الجميع.
 */
export function toLatinDigits(value: string): string {
  return value.replace(/[٠-٩]/g, (digit) => String(digit.charCodeAt(0) - 0x0660));
}

/**
 * المقارنة بعد التنظيف.
 * ولا تُقارَن الأطوال المختلفة: رمزٌ ناقص خانةً ليس بدايةَ رمز صحيح.
 */
export function sameJoinCode(entered: string, expected: string): boolean {
  const left = normalizeJoinCode(entered);
  const right = normalizeJoinCode(expected);
  return left.length === JOIN_CODE_DIGITS && left === right;
}
