/**
 * بوّابة مساعدة الطالب — PRD §23 · قرار D10.
 *
 * الـ PRD ينصّ: «AI للطلاب **مطفأ افتراضياً**، ويحتاج تفعيلاً صريحاً لكل
 * فصل/نشاط». واللوح `T19` كان يعرض مفتاحاً عاماً واحداً — والفرق بينهما هو
 * الفرق `D-2`، وأُغلق بالقرار `D10`:
 *
 *   القاطع العام في T19  ⇦ يُطفئ كل شيء حين يُطفأ.
 *   مفتاح الفصل في T08    ⇦ فصلٌ يسمح وآخر لا.
 *   مفتاح النشاط في T16   ⇦ نشاطٌ يسمح وآخر لا (يأتي مع الأنشطة في Phase 5).
 *
 * **كلها يجب أن تكون مفتوحة.** والافتراضي في كل مستوى `false`: مفتاحٌ جديد
 * يُضاف لاحقاً يبدأ مطفأً، فلا يفتح تحديثُ التطبيق باباً لم يفتحه المعلم.
 */

/**
 * السياق يُصرَّح به ولا يُستنتج من غياب حقل.
 *
 * **العطل الذي يمنعه هذا الشكل:** كان الحقل اختيارياً و`undefined` تمرّ. فمن
 * يبني سطح مساعدةٍ داخل نشاط وينسى تمرير مفتاحه يحصل على **سماحٍ صامت** —
 * وهو بالضبط ما وُضع القرار `D10` ليمنعه: «مفتاحٌ يُضاف لاحقاً يبدأ مطفأً،
 * فلا يفتح تحديثُ التطبيق باباً لم يفتحه المعلم».
 *
 * والآن `context: 'activity'` يوجب `activityEnabled`، فالنسيان **لا يُترجم**
 * أصلاً. حارسٌ يفرضه المترجم أقوى من حارسٍ يفرضه انتباه من يكتب.
 */
export type StudentAiGates =
  | {
      /** مساعدة داخل درس — لا مفتاح نشاط في هذا السياق. */
      readonly context: 'lesson';
      readonly master: boolean;
      readonly classEnabled: boolean;
    }
  | {
      /** مساعدة داخل نشاط — المفتاح الثالث **مطلوب**، لا اختياري. */
      readonly context: 'activity';
      readonly master: boolean;
      readonly classEnabled: boolean;
      readonly activityEnabled: boolean;
    };

export function studentAiAllowed(gates: StudentAiGates): boolean {
  if (!gates.master) return false;
  if (!gates.classEnabled) return false;
  if (gates.context === 'activity' && !gates.activityEnabled) return false;
  return true;
}

