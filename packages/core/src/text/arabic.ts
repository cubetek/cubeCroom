/**
 * تطبيع الأسماء العربية للمقارنة.
 *
 * تنبيه T10 «اسم مشابه لطالب مقبول بالفعل» لا يعمل بمقارنة نصّية مباشرة:
 * «عبد الرحمن» و«عبدالرحمن» و«عبدالرحمن» بتشكيل، ثلاثتها اسم واحد يكتبه
 * ثلاثة طلاب بثلاث طرق — ومقارنةٌ حرفية تمرّرها جميعاً فلا يظهر التنبيه حين
 * يكون أنفع ما يكون.
 *
 * والتطبيع للمقارنة وحدها: الاسم يُخزَّن ويُعرض كما كتبه الطالب.
 */

/**
 * التشكيل والتطويل — زينة إملائية لا تغيّر الاسم.
 *
 * `\p{Mn}` لا قائمةَ محارف مكتوبة: محرف تشكيل مكتوبٌ حرفياً داخل صنف يلتصق
 * بصرياً بما قبله في الملف فيُقرأ محرفاً واحداً وهو محرفان — وهي بالضبط
 * الحالة التي تمنعها قاعدة `no-misleading-character-class`. والخاصية تغطي
 * الحركات والتنوين والسكون والألف الخنجرية معاً، فلا تفوت واحدة نسيناها.
 * ويُضاف إليها التطويل U+0640 لأنه ليس علامة تشكيل بل حرف مدّ زخرفي.
 */
const MARKS = /[\p{Mn}\u0640]/gu;

export function normalizeArabic(value: string): string {
  return value
    .normalize('NFKC')
    .replace(MARKS, '')
    .replace(/[أإآٱ]/gu, 'ا')
    .replace(/ى/gu, 'ي')
    .replace(/ة/gu, 'ه')
    .replace(/ؤ/gu, 'و')
    .replace(/ئ/gu, 'ي')
    .replace(/\s+/gu, ' ')
    .trim()
    .toLowerCase();
}

/**
 * اسمان يقصدان الشخص نفسه على الأرجح.
 *
 * التشابه يُحسب بعد حذف المسافات أيضاً، ليلتقط «عبد الرحمن» و«عبدالرحمن».
 * والنتيجة **تنبيه لا منع**: القرار للمعلم، وقد يكون في الفصل أخوان باسم
 * واحد فعلاً.
 */
export function similarNames(a: string, b: string): boolean {
  const left = normalizeArabic(a);
  const right = normalizeArabic(b);
  if (left === '' || right === '') return false;
  return left === right || left.replace(/ /gu, '') === right.replace(/ /gu, '');
}
