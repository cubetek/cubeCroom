'use client';

import { useEffect, useRef, useState } from 'react';
import { Alert, Card } from '@cubecroom/ui';

/**
 * حارس الصلة بجهاز المعلم — S09 وما حوله.
 *
 * **المشكلة التي يحلّها:** إنهاء الحصة يُوقف عملية خادم الطلاب كلّها لا الرمز
 * وحده. فصفحةٌ لا تسأل الخادم عن شيء — عارضُ الدرس، وصفحةُ النشاط، والإيصال —
 * تبقى معروضة كما هي، ثم يَنقر الطالب رابطاً فيرى **صفحة خطأ من متصفّحه**:
 * إنكليزية، تقنية، ولا تقول له ماذا يفعل.
 *
 * فتسأل هذه الأداة سؤالاً واحداً رخيصاً كل ثلاث ثوانٍ، وتُبدّل الشاشة قبل أن
 * ينقر. والنقرة التي كانت تقوده إلى خطأ المتصفّح لم تعد موجودة أصلاً.
 *
 * **ولماذا ليست Service Worker:** عامل الخدمة يحتاج «سياقاً آمناً»، وعنوان
 * الحصة `http://192.168.4.20:4317` ليس كذلك — فـ`navigator.serviceWorker`
 * **غير موجود** على جهاز الطالب أصلاً (مفحوص، لا مفترض). وهو موجود على
 * `127.0.0.1` أي على جهاز المعلم وحده — ولا طالب هناك.
 */

export type LinkState = 'live' | 'lost' | 'ended';

/**
 * ثلاث ثوانٍ بين نبضة وأخرى، وثلاث محاولات قبل الحكم — أي **تسع ثوانٍ**
 * تُكتشف فيها القطيعة.
 *
 * **ولماذا نزلت من عشر:** بين نبضتين نافذةٌ يستطيع الطالب أن ينقر فيها رابطاً
 * فيرى خطأ المتصفّح قبل أن تُبدَّل شاشته — وطول النافذة هو طول ما بقي مكشوفاً
 * بعد كل هذا العمل. وثلاث ثوانٍ هي إيقاع استطلاع شاشة الانتظار نفسه (S02)،
 * فلا إيقاعان في سطح واحد.
 *
 * **والثمن مقيسٌ لا مقدَّر:** ثلاثون طالباً على هذا الإيقاع = عشرة طلبات في
 * الثانية على خادم في الغرفة نفسها — يقيسها اختبار الحِمل ويثبت أنها لا تُبطئ
 * ما يفعله الطالب فعلاً.
 *
 * وتبقى المحاولات ثلاثاً لا اثنتين: تعثّرة Wi-Fi في صفٍّ مدرسيّ أقصر من تسع
 * ثوانٍ غالباً، وشاشةٌ تُبدَّل لتعثّرة ثم تعود أسوأ من انتظار قصير.
 */
const PATIENCE = 3;
const EVERY_MS = 3000;

export function useTeacherLink(): LinkState {
  const [state, setState] = useState<LinkState>('live');
  const misses = useRef(0);

  useEffect(() => {
    let alive = true;

    const ask = async () => {
      try {
        const response = await fetch('/api/student/ping', { cache: 'no-store' });
        if (!alive) return;
        misses.current = 0;
        /*
         * ٤٠٣ من خادمٍ يردّ حالةٌ نعرفها يقيناً: الرمز أُبطل والحصة انتهت.
         * وهي تختلف عن الصمت — ولذلك لها نصّها الجازم.
         */
        setState(response.ok ? 'live' : 'ended');
      } catch {
        if (!alive) return;
        misses.current += 1;
        if (misses.current >= PATIENCE) setState('lost');
      }
    };

    void ask();
    const timer = setInterval(() => void ask(), EVERY_MS);
    return () => {
      alive = false;
      clearInterval(timer);
    };
  }, []);

  return state;
}

/**
 * الشاشة التي يراها الطالب حين تنقطع الصلة.
 *
 * نصّان لا نصّ واحد، لأن ما نعرفه يختلف:
 *
 *   • **`ended`** — الخادم ردّ ورفض: الحصة انتهت يقيناً، فيُقال ذلك.
 *   • **`lost`** — لم يردّ أحد: قد يكون معلمه أنهى الحصة، وقد يكون جهازه خرج
 *     من مدى Wi-Fi. والأثر واحد بالضبط، فلا يُخمَّن السبب: طفلٌ خرج من
 *     التغطية يُقال له «أنهى معلمك الحصة» يظنّ أنه أُخرج من صفّه.
 */
export function LinkNotice({ state }: { readonly state: LinkState }) {
  if (state === 'live') return null;

  /*
   * القياسات هي قياسات بطاقات الطالب نفسها: الطالب لا يشعر أنه انتقل إلى
   * تطبيق آخر لأن الاتصال انقطع. والبطاقة في وسط الشاشة رأسياً وأفقياً —
   * لا محتوى غيرها.
   */
  return (
    <main className="flex min-h-svh items-center justify-center p-5">
      <Card className="w-full max-w-[360px] gap-2.5 px-6 py-6">
        {state === 'ended' ? (
          <>
            <h1 className="text-s-h1">انتهت الحصة</h1>
            <p className="text-s-body text-text-2">
              أنهى معلمك جلسة الدخول. لن تستطيع فتح الفصل حتى يشغّلها مرة أخرى في الحصة القادمة.
            </p>
          </>
        ) : (
          <>
            <h1 className="text-s-h1">انقطع الاتصال بجهاز معلمك</h1>
            <p className="text-s-body text-text-2">
              إمّا أنهى معلمك الحصة، وإمّا خرج جهازك من شبكة Wi-Fi. أبقِ هذه الصفحة مفتوحة — تعود
              وحدها متى عاد الاتصال.
            </p>
          </>
        )}
        {/*
         * الطمأنة أولاً: الطالب يخاف على ما أرسله قبل أن يسأل عن السبب.
         * و`live` مرفوعة عن قصد — اللوح يُرسم مع الشاشة كلّها لا جواباً على
         * فعلٍ للتوّ، فلا يقاطع به قارئُ الشاشة قارئَه.
         */}
        {/*
          `text-s-caption` بيده: `Alert` مبنيّ بمقياس المعلّم (`text-t-label`)،
          و`data-app="student"` لا يبدّل منه إلا `--height-control`.
        */}
        <Alert tone="ok" className="text-s-caption">
          كل ما أرسلته وصل إلى معلمك ومحفوظ عنده — لم يضِع شيء.
        </Alert>
      </Card>
    </main>
  );
}

/**
 * يلفّ محتوى الصفحة: يعرضه ما دامت الصلة قائمة، ويُبدّله حين تنقطع.
 *
 * والاستبدال لا الطبقة فوقه: محتوى درسٍ لم يعد الطالب يملك الوصول إليه لا
 * يبقى مقروءاً خلف رسالة.
 */
export function LinkWatch({ children }: { readonly children: React.ReactNode }) {
  const state = useTeacherLink();
  if (state === 'live') return <>{children}</>;
  return <LinkNotice state={state} />;
}
